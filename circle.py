import math


def area(r):
    '''
    Returns area of the circle

    Parameters:
        r: radius of the circle

    Return value
        : area of the circle
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Returns perimeter of the circle

    Parameters:
        r: radius of the circle

    Return value
        : perimeter of the circle
    '''
    return 2 * math.pi * r

